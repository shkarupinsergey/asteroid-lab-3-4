from pathlib import Path
from graphics import Image

SPACESHIP_WIDTH = 100
SPACESHIP_HEIGHT = 150
SPACESHIP_ACTIVE_HEIGHT = 184
MAX_SPEED = 15
SPACESHIP_LIFETIME = 50
ASTEROID_SPEED_MULTIPLIER = 1
ROCKET_SPEED = 10
ROCKET_MAX_TICKS = 50

FULLSCREEN = True
GAME_TITLE = "Космический штурмовой корабль"

PROJECT_DIR = Path(__file__).resolve().parent
IMAGES_DIR = PROJECT_DIR / "images"

START_BACKGROUND_IMAGE_PATH = IMAGES_DIR / "start_background_dark.png"
GAME_BACKGROUND_IMAGE_PATH = IMAGES_DIR / "background.png"
SPACESHIP_IMAGE_PATH = IMAGES_DIR / "spaceship.png"
SPACESHIP_ACTIVE_IMAGE_PATH = IMAGES_DIR / "spaceship_active.png"
ASTEROID_IMAGE_PATH = IMAGES_DIR / "asteroid.png"
ASTEROID_IMAGE2_PATH = IMAGES_DIR / "asteroid2.png"
ASTEROID_DESTROY_IMAGE_PATH = IMAGES_DIR / "asteroid_destroy.png"
LIFE_IMAGE_PATH = IMAGES_DIR / "life.png"

START_BACKGROUND_IMAGE = None
GAME_BACKGROUND_IMAGE = None
SPACESHIP_IMAGE = None
SPACESHIP_ACTIVE_IMAGE = None
ASTEROID_IMAGES = None
ASTEROID_DESTROY_IMAGE = None
LIFE_IMAGE = None

def load_images():
    global START_BACKGROUND_IMAGE, GAME_BACKGROUND_IMAGE, SPACESHIP_IMAGE, SPACESHIP_ACTIVE_IMAGE
    global ASTEROID_IMAGES, ASTEROID_DESTROY_IMAGE, LIFE_IMAGE
    START_BACKGROUND_IMAGE = Image.open(START_BACKGROUND_IMAGE_PATH)

    GAME_BACKGROUND_IMAGE = Image.open(GAME_BACKGROUND_IMAGE_PATH)

    SPACESHIP_IMAGE = Image.open(SPACESHIP_IMAGE_PATH)
    SPACESHIP_IMAGE = SPACESHIP_IMAGE.resize((SPACESHIP_WIDTH, SPACESHIP_HEIGHT))

    SPACESHIP_ACTIVE_IMAGE = Image.open(SPACESHIP_ACTIVE_IMAGE_PATH)
    SPACESHIP_ACTIVE_IMAGE = SPACESHIP_ACTIVE_IMAGE.resize(
        (SPACESHIP_WIDTH, SPACESHIP_ACTIVE_HEIGHT)
    )


    ASTEROID_IMAGES = [
        Image.open(ASTEROID_IMAGE_PATH),
        Image.open(ASTEROID_IMAGE2_PATH)
    ]

    ASTEROID_DESTROY_IMAGE = Image.open(ASTEROID_DESTROY_IMAGE_PATH)

    LIFE_IMAGE = Image.open(LIFE_IMAGE_PATH)
    LIFE_IMAGE = LIFE_IMAGE.resize((30, 30))
